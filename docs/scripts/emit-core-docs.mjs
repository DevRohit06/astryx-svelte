// Emits `packages/core`'s own `.doc.mjs` files.
//
// `@astryx-svelte/cli` reads component and hook prose out of core the way
// upstream's CLI reads it out of `@astryxdesign/core`: co-located `.doc.mjs`
// modules, discovered by walking the published `src/` tree. This port shipped
// none, which is why `searchComponents`' Pass 2 finds nothing today (TODO.md,
// slice 2) and why the doc-driven commands — `component`, `util` / `hook`,
// `docs`, `search`, `discover` — are blocked.
//
// They are **generated, not authored**, and both halves of that matter:
//
//   - The prose is upstream's, reused verbatim. Writing it again would be
//     inventing documentation for components ported to be identical.
//   - The types are **not** upstream's. `.doc.mjs` states each prop's type as a
//     string, and upstream's strings are React (`ReactNode`,
//     `ReactElement<IconProps>`). Copying them would publish an API this
//     library does not have — `Button.icon` is `Snippet` here with no string
//     branch, the case CLAUDE.md names.
//
// `generate-content.mjs` already reconciles exactly those two sources for the
// docs site, so this script reuses that reconciliation rather than repeating
// it: `reconcile()` returns the entries, and everything below is reshaping.
//
// The output layout follows from the same measurement TODO.md's slice-2 entry
// records — name → directory is not a function, so **the barrel is the index**.
// Each entry is written next to the module its export resolves to, under the
// export's own name: `BreadcrumbMenuItem` is `dropdown-menu-item.svelte`, so it
// lands as `components/dropdown-menu/BreadcrumbMenuItem.doc.mjs`. PascalCase /
// camelCase filenames beside kebab-case sources looks inconsistent, and is
// upstream's convention (`Text/Heading.doc.mjs`, `useResizable.doc.mjs`); it is
// also the only collision-free choice, since `dropdown-menu-item.svelte`
// documents both `ContextMenuItem` and `DropdownMenuItem` and `i18n/index.js`
// documents both `InternationalizationProvider` and `useTranslator`.
//
// **No name → source index file is emitted.** Upstream's
// `foundation/discovery/component-discovery.mjs` walks the tree and reads
// `package.json#exports`; the co-located docs *are* the index. An index would
// have to be built by the TypeScript compiler, and keeping `typescript` out of
// the CLI's runtime dependencies is a hard constraint.
//
// Run it with `pnpm -F docs emit-core-docs`. It is deliberately **not** wired
// into `pnpm -F docs generate` or any `build`: a build that writes into another
// workspace package's source tree is not hermetic, and `pnpm -r build` orders
// docs after core, so the files would land a step too late to be packed.
//
// `--check` is the same run as an assertion — it writes nothing and fails on a
// doc that is missing, stale or orphaned. That is docs' `test` script, so
// `pnpm -r test` fails if the committed files stop matching what this emitter
// produces, rather than the emitted output being trusted because it was correct
// once.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import prettier from 'prettier';
import { reconcile } from './generate-content.mjs';
// Reached by path rather than by package specifier, exactly as this pipeline
// already reaches `packages/core/dist` and `packages/core/package.json`. A
// `@astryx-svelte/cli` dependency on `docs` would buy the `./doc` subpath and
// nothing else, and this script's whole job is to write files *for* that
// package — a declared edge would suggest a coupling that does not exist.
import { parseDoc } from '../../packages/cli/authoring/doctypes/parse.mjs';

const DOCS_ROOT = fileURLToPath(new URL('..', import.meta.url));
const WORKSPACE_ROOT = path.join(DOCS_ROOT, '..');
const CORE_ROOT = path.join(WORKSPACE_ROOT, 'packages', 'core');
const CORE_SRC = path.join(CORE_ROOT, 'src', 'lib');

const HEADER =
	'// @generated by docs/scripts/emit-core-docs.mjs — do not edit.\n' +
	'//\n' +
	"// Prose is upstream's, verbatim. Every `type` is read from this package's own\n" +
	"// compiled declarations rather than upstream's React ones, which is why this\n" +
	'// file is generated instead of copied.\n';

// ---------------------------------------------------------------------------
// the contract
// ---------------------------------------------------------------------------

// `packages/cli/authoring/doctypes/{base,component,hook}/type.ts` is the
// contract, and these are its nested object shapes spelled out as key sets.
//
// They are checked rather than filtered, and the difference is the point. A
// filter drops an unrecognised upstream field silently, which is how a doc
// grows a member nobody notices for two releases. Throwing means a new upstream
// field is a one-line decision — declare it in the doctype or state why it is
// dropped — taken the first time it appears. Every one of these matched
// upstream's authored keys exactly when the emitter was written.

const USAGE_FIELDS = new Set(['description', 'bestPractices', 'anatomy']);
const BEST_PRACTICE_FIELDS = new Set(['guidance', 'description']);
const ANATOMY_FIELDS = new Set(['name', 'required', 'description']);
const THEMING_FIELDS = new Set(['container', 'targets', 'vars', 'derived']);
const THEMING_TARGET_FIELDS = new Set(['className', 'visualProps', 'states']);
const THEMING_VAR_FIELDS = new Set([
	'name',
	'description',
	'default',
	'derived',
	'formula',
	'private'
]);
const THEMING_DERIVED_FIELDS = new Set(['property', 'vars', 'expand']);
const PLAYGROUND_FIELDS = new Set(['defaults', 'overlay', 'wrapper']);
const PLAYGROUND_WRAPPER_FIELDS = new Set(['component', 'props']);

/**
 * Throw unless every key of `value` is declared by the doctype.
 *
 * @param {Record<string, any> | null | undefined} value
 * @param {Set<string>} declared
 * @param {string} where
 */
function assertDeclared(value, declared, where) {
	if (value == null) return;
	const undeclared = Object.keys(value).filter((key) => !declared.has(key));
	if (undeclared.length === 0) return;
	throw new Error(
		`[emit-core-docs] ${where} carries ${undeclared.length} field(s) the CLI's doc ` +
			`contract does not declare: ${undeclared.join(', ')}.\n` +
			`  packages/cli/authoring/doctypes/ is the contract. Either declare the field ` +
			`there or record here why it is dropped — do not widen the key set silently.`
	);
}

/**
 * A `UsageDoc`, checked field by field.
 *
 * @param {Record<string, any>} usage
 * @param {string} where
 */
function usageDoc(usage, where) {
	assertDeclared(usage, USAGE_FIELDS, `${where} usage`);
	for (const practice of usage.bestPractices ?? []) {
		assertDeclared(practice, BEST_PRACTICE_FIELDS, `${where} usage.bestPractices[]`);
	}
	for (const element of usage.anatomy ?? []) {
		assertDeclared(element, ANATOMY_FIELDS, `${where} usage.anatomy[]`);
	}
	return usage;
}

/**
 * A `ComponentBaseDoc['theming']`, checked field by field.
 *
 * @param {Record<string, any>} theming
 * @param {string} where
 */
function themingDoc(theming, where) {
	assertDeclared(theming, THEMING_FIELDS, `${where} theming`);
	for (const target of theming.targets ?? []) {
		assertDeclared(target, THEMING_TARGET_FIELDS, `${where} theming.targets[]`);
	}
	for (const variable of theming.vars ?? []) {
		assertDeclared(variable, THEMING_VAR_FIELDS, `${where} theming.vars[]`);
	}
	for (const derived of theming.derived ?? []) {
		assertDeclared(derived, THEMING_DERIVED_FIELDS, `${where} theming.derived[]`);
	}
	return theming;
}

/**
 * A `ComponentPlaygroundConfig`. Already normalised through
 * `normalisePlayground`'s allowlist, so this only re-states the contract.
 *
 * @param {Record<string, any>} playground
 * @param {string} where
 */
function playgroundDoc(playground, where) {
	assertDeclared(playground, PLAYGROUND_FIELDS, `${where} playground`);
	assertDeclared(playground.wrapper, PLAYGROUND_WRAPPER_FIELDS, `${where} playground.wrapper`);
	return playground;
}

/**
 * One `ComponentPropDoc` / `HookParamDoc` row.
 *
 * The reconciled row carries more than this: `unverified`, `unsupported`,
 * `upstreamType`, `renamedFrom` and `correctedFromUpstream` are the docs site's
 * provenance annotations, and the CLI's contract declares none of them. Where
 * they change what a reader sees they have already been applied — a corrected
 * `default` is emitted as the corrected value — so what is dropped is the
 * explanation, not the answer.
 *
 * @param {Record<string, any>} row
 * @param {string} where
 */
function propRow(row, where) {
	if (!row.name) throw new Error(`[emit-core-docs] ${where} has a row with no name`);
	if (!row.type) throw new Error(`[emit-core-docs] ${where}.${row.name} has no type`);

	/** @type {Record<string, any>} */
	const out = { name: row.name, type: row.type, description: row.description ?? '' };
	if (row.default != null) out.default = row.default;
	if (row.required === true) out.required = true;
	return out;
}

/**
 * One `HookReturnDoc` row — three fields, and no `default` or `required`: a
 * return value has neither, and `HookReturnDoc` declares neither.
 *
 * @param {Record<string, any>} row
 * @param {string} where
 */
function returnRow(row, where) {
	if (!row.name) throw new Error(`[emit-core-docs] ${where} has a return row with no name`);
	if (!row.type) throw new Error(`[emit-core-docs] ${where}.${row.name} has no type`);
	return { name: row.name, type: row.type, description: row.description ?? '' };
}

// ---------------------------------------------------------------------------
// entry → doc
// ---------------------------------------------------------------------------

/**
 * A `HookDoc`, stamped `type: 'function'`.
 *
 * Key order follows the interface's own declaration order, so a reader can hold
 * the type and the file side by side.
 *
 * @param {Record<string, any>} entry
 */
function hookDoc(entry) {
	const where = entry.name;
	if (!entry.usage) throw new Error(`[emit-core-docs] ${where}: HookDoc requires usage`);

	/** @type {Record<string, any>} */
	const doc = { type: 'function', name: entry.name, displayName: entry.displayName };
	if (entry.group) doc.group = entry.group;
	if (entry.keywords?.length) doc.keywords = entry.keywords;
	doc.params = (entry.params ?? []).map((row) => propRow(row, `${where}.params`));
	doc.returns = (entry.returns ?? []).map((row) => returnRow(row, `${where}.returns`));
	doc.usage = usageDoc(entry.usage, where);
	// Upstream's own lists, verbatim. Three of them name a component this port
	// does not export — see the run's report and TODO.md; they are upstream's
	// prose and are not silently rewritten here.
	if (entry.relatedComponents?.length) doc.relatedComponents = entry.relatedComponents;
	if (entry.relatedHooks?.length) doc.relatedHooks = entry.relatedHooks;
	doc.importPath = entry.importPath;
	if (entry.category) doc.category = entry.category;
	return doc;
}

/**
 * A `SingleComponentDoc` or a `SubComponentDoc`, both stamped
 * `type: 'component'`.
 *
 * Which one is decided by the entry, not by a preference. `SingleComponentDoc`
 * requires `usage`, and 81 of the 209 entries do not have one — they carry a
 * one-line `description` instead, the way a `components[]` member does.
 * `SubComponentDoc` is the union member written for exactly that (`usage`
 * optional, `description` and `subComponentOf` required), and all 81 resolve to
 * it because `flattenDoc` now records each member's parent. Neither field is
 * synthesised: an entry fitting neither shape fails the run rather than getting
 * invented prose.
 *
 * @param {Record<string, any>} entry
 */
function componentDoc(entry) {
	const where = entry.name;

	/** @type {Record<string, any>} */
	const doc = { type: 'component', name: entry.name, displayName: entry.displayName };

	if (entry.subComponentOf) {
		doc.subComponentOf = entry.subComponentOf;
		if (!entry.description) {
			throw new Error(
				`[emit-core-docs] ${where} is a sub-component of ${entry.subComponentOf} but has ` +
					`no description. SubComponentDoc requires one and there is nothing honest to ` +
					`put there.`
			);
		}
		doc.description = entry.description;
	} else if (!entry.usage) {
		throw new Error(
			`[emit-core-docs] ${where} has neither a usage block nor a parent, so it fits ` +
				`neither SingleComponentDoc nor SubComponentDoc.`
		);
	}
	// 47 entries carry a top-level `description` *and* a `usage`, and there the
	// description is dropped. Not for tidiness: `ComponentBaseDoc` does not
	// declare it, and every read of it in upstream's CLI is spelled
	// `docs.usage?.description || docs.description`, so with a usage block
	// present it is unreachable on all 47.

	if (entry.keywords?.length) doc.keywords = entry.keywords;
	if (entry.hiddenComponents?.length) doc.hiddenComponents = entry.hiddenComponents;
	if (entry.hidden) doc.hidden = true;
	if (entry.group) doc.group = entry.group;
	if (entry.category) doc.category = entry.category;
	if (entry.isHiddenFromOverview) doc.isHiddenFromOverview = true;
	if (entry.theming) doc.theming = themingDoc(entry.theming, where);
	if (entry.usage) doc.usage = usageDoc(entry.usage, where);
	if (entry.playground) doc.playground = playgroundDoc(entry.playground, where);
	doc.props = (entry.props ?? []).map((row) => propRow(row, `${where}.props`));
	return doc;
}

/**
 * @param {Record<string, any>} entry
 */
const docFor = (entry) => (entry.isHook ? hookDoc(entry) : componentDoc(entry));

// ---------------------------------------------------------------------------
// placement
// ---------------------------------------------------------------------------

/**
 * Where an entry's doc file belongs — the directory of the module its export
 * resolves to, under the export's own name.
 *
 * @param {string} name
 * @param {Map<string, string>} sourceModuleByName
 * @returns {string} absolute path
 */
function outFileFor(name, sourceModuleByName) {
	const specifier = sourceModuleByName.get(name);
	if (!specifier) {
		throw new Error(
			`[emit-core-docs] ${name} is documented and exported, but no entry point re-exports ` +
				`it from a module, so there is no directory to put its doc in. The barrel is the ` +
				`index; a name it cannot resolve is a real gap, not a placement problem.`
		);
	}

	// `components/button/button.svelte` → `components/button`; a module at the
	// package root yields `.`, which resolves to `src/lib` itself.
	const relative = path.posix.dirname(specifier);
	const dir = path.join(CORE_SRC, relative === '.' ? '' : relative);

	if (!fs.existsSync(dir)) {
		throw new Error(
			`[emit-core-docs] ${name} resolves to ${specifier}, whose directory does not exist ` +
				`under src/lib: ${dir}. dist/ and src/ have diverged — rebuild core.`
		);
	}

	return path.join(dir, `${name}.doc.mjs`);
}

// ---------------------------------------------------------------------------
// emit
// ---------------------------------------------------------------------------

/**
 * Render one doc as a formatted module.
 *
 * `JSON.stringify` first, then prettier — rather than hand-building the
 * literal — because prettier's own output is what `prettier --check` compares
 * against, and because `JSON.stringify` escapes control characters instead of
 * writing them. A raw U+0000 in a source file has cost this repo three
 * debugging sessions; the escape is the only safe way to emit one.
 *
 * @param {unknown} doc
 * @param {string} file
 * @param {import('prettier').Options | null} prettierOptions
 */
async function render(doc, file, prettierOptions) {
	const source = `${HEADER}\nexport default ${JSON.stringify(doc, null, '\t')};\n`;
	return prettier.format(source, { ...prettierOptions, filepath: file });
}

/**
 * Every `*.doc.mjs` currently under `src/lib`.
 *
 * @param {string} dir
 * @param {string[]} [found]
 * @returns {string[]}
 */
function findEmitted(dir, found = []) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) findEmitted(full, found);
		else if (entry.isFile() && entry.name.endsWith('.doc.mjs')) found.push(full);
	}
	return found;
}

/**
 * The entries whose upstream doc carries `examples`, which this port emits
 * **without** them — deliberately, and this list is what keeps that deliberate.
 *
 * `ComponentBaseDoc.examples` is a real field and upstream's CLI renders it
 * after the props table, so dropping it is a gap rather than a tidy-up. It is
 * dropped anyway because upstream's `code` is **JSX** — a React function
 * component, `<Field status={{type: 'success'}}>`, `defaultValue` — while this
 * port's own `ComponentExampleDoc.code` is documented as "Svelte source for the
 * example". Emitting it verbatim would ship React source as this CLI's answer
 * to "show me an example", which is the `Button.icon` mistake CLAUDE.md names:
 * upstream's prose is reusable, upstream's *code* is not. Translating ten
 * examples by hand is real work and is tracked in TODO.md; inventing them here
 * is not on the table.
 *
 * The list is exact on the class oracle's `skip` rule. An entry that stops
 * carrying examples fails the run, and so does one that starts — either way the
 * comment above has gone out of date and someone has to look.
 */
const UPSTREAM_EXAMPLES_NOT_PORTED = new Set([
	'AvatarGroupOverflow',
	'CheckboxListItem',
	'DialogHeader',
	'Field',
	'InternationalizationProvider',
	'Markdown',
	'Outline',
	'useTableRowExpansion',
	'useTableSelection',
	'useTableTreeData'
]);

/**
 * Fail when the set of entries carrying upstream examples has moved.
 *
 * @param {Array<Record<string, any>>} entries
 */
function assertExampleDeferralIsCurrent(entries) {
	const carrying = new Set(
		entries.filter((entry) => entry.upstreamExamples?.length).map((entry) => entry.name)
	);
	const appeared = [...carrying].filter((name) => !UPSTREAM_EXAMPLES_NOT_PORTED.has(name));
	const gone = [...UPSTREAM_EXAMPLES_NOT_PORTED].filter((name) => !carrying.has(name));
	if (appeared.length === 0 && gone.length === 0) return;

	throw new Error(
		`[emit-core-docs] the upstream-examples deferral is out of date.\n` +
			(appeared.length ? `    now carrying examples: ${appeared.join(', ')}\n` : '') +
			(gone.length ? `    no longer carrying:    ${gone.join(', ')}\n` : '') +
			`  These entries are emitted without their examples because upstream's are JSX.\n` +
			`  Update UPSTREAM_EXAMPLES_NOT_PORTED and the TODO.md entry that counts them.`
	);
}

/**
 * @param {string} file
 * @param {string} contents
 */
function writeIfChanged(file, contents) {
	if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === contents) return false;
	fs.writeFileSync(file, contents, 'utf8');
	return true;
}

/**
 * @param {{check?: boolean, quiet?: boolean}} [options]
 */
export async function emitCoreDocs({ check = false, quiet = false } = {}) {
	/** @type {(...args: unknown[]) => void} */
	const log = quiet ? () => {} : (...args) => console.log(...args);

	const { surface, entries } = await reconcile({ quiet });

	assertExampleDeferralIsCurrent(entries);

	// Resolved for `src/lib` rather than for each file: they all sit under
	// `packages/core`, so they all resolve the same `prettier.config.js`, and
	// resolving it 209 times would only mean 209 identical answers.
	const prettierOptions = await prettier.resolveConfig(path.join(CORE_SRC, 'probe.doc.mjs'));
	if (!prettierOptions) {
		throw new Error(
			`[emit-core-docs] no prettier config resolved for ${CORE_SRC}. The emitted files ` +
				`must satisfy \`prettier --check\`, so formatting them with defaults would ` +
				`guarantee a lint failure rather than risk one.`
		);
	}

	/** @type {Map<string, string>} absolute file → formatted contents */
	const planned = new Map();

	for (const entry of entries) {
		const file = outFileFor(entry.name, surface.sourceModuleByName);
		if (planned.has(file)) {
			throw new Error(`[emit-core-docs] two entries claim ${file}`);
		}
		const doc = docFor(entry);
		// The CLI's own load boundary, run on every doc before it is written. A
		// doc the CLI cannot load is worthless, and this is the one check that
		// asks the real question rather than a proxy for it.
		parseDoc(doc, path.relative(WORKSPACE_ROOT, file));
		planned.set(file, await render(doc, file, prettierOptions));
	}

	const existing = findEmitted(CORE_SRC);
	const stale = existing.filter((file) => !planned.has(file));

	/**
	 * The differing lines, for a `--check` failure.
	 *
	 * "stale" on its own is only actionable where you can re-run the emitter and
	 * read the diff yourself. It is not actionable in CI, where the emitted
	 * output is the thing that differs from the committed file and the run that
	 * produced it is gone — which is exactly the case this was added for: four
	 * docs that are current on one machine and stale on another, with nothing in
	 * the message to say what moved.
	 *
	 * @param {string} file
	 * @param {string} planned  what this run would write
	 * @returns {string}
	 */
	function diffFor(file, planned) {
		const before = fs.readFileSync(file, 'utf8').split('\n');
		const after = planned.split('\n');
		/** @type {string[]} */
		const lines = [];

		for (let i = 0; i < Math.max(before.length, after.length) && lines.length < 24; i++) {
			if (before[i] === after[i]) continue;
			if (before[i] !== undefined) lines.push(`      -${i + 1}: ${before[i]}`);
			if (after[i] !== undefined) lines.push(`      +${i + 1}: ${after[i]}`);
		}

		return (
			`\n\n  ${path.relative(WORKSPACE_ROOT, file)} — committed (-) vs emitted (+):\n` +
			lines.join('\n') +
			(lines.length >= 24 ? '\n      … truncated' : '')
		);
	}

	if (check) {
		const missing = [...planned.keys()].filter((file) => !fs.existsSync(file));
		const changed = [...planned].filter(
			([file, contents]) => fs.existsSync(file) && fs.readFileSync(file, 'utf8') !== contents
		);
		const problems = [
			...missing.map((f) => `missing:  ${path.relative(WORKSPACE_ROOT, f)}`),
			...changed.map(([f]) => `stale:    ${path.relative(WORKSPACE_ROOT, f)}`),
			...stale.map((f) => `orphaned: ${path.relative(WORKSPACE_ROOT, f)}`)
		];
		if (problems.length > 0) {
			throw new Error(
				`[emit-core-docs] ${problems.length} file(s) out of date:\n` +
					problems.map((p) => `    ${p}`).join('\n') +
					changed.map(([file, contents]) => diffFor(file, contents)).join('') +
					`\n  Run \`pnpm -F docs emit-core-docs\` and commit the result.`
			);
		}
		log(`  checked     ${planned.size} doc(s), all current`);
		return { emitted: planned.size, changed: 0, removed: 0 };
	}

	let changed = 0;
	for (const [file, contents] of planned) {
		if (writeIfChanged(file, contents)) changed++;
	}
	// An entry that is renamed or unexported would otherwise leave its doc
	// behind, where the CLI would keep listing a component core no longer has.
	for (const file of stale) fs.rmSync(file);

	const hooks = entries.filter((entry) => entry.isHook).length;
	log(
		`  docs        ${planned.size} emitted (${planned.size - hooks} components, ${hooks} hooks), ` +
			`${changed} changed, ${stale.length} removed`
	);

	return { emitted: planned.size, changed, removed: stale.length };
}

// Run directly (`node scripts/emit-core-docs.mjs [--check]`).
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	const check = process.argv.includes('--check');
	console.log(check ? 'checking core docs…' : 'emitting core docs…');
	emitCoreDocs({ check }).catch((error) => {
		console.error(`\nemit-core-docs failed: ${error.message}\n`);
		process.exit(1);
	});
}
