// Compiles the docsite's own Astryx brand theme into
// src/lib/generated/astryx-theme.css.
//
// Upstream builds this theme with `astryx theme build` and imports the artifact
// from `globals.css` (`@import "../themes/astryx.css"`). The reason it is built
// rather than injected at runtime is written down in upstream's page.tsx: an
// unbuilt theme object makes `<Theme>` inject a stylesheet on mount, and the
// landing page mounts several of them. `__built: true` on the exported object is
// what turns that off; this script is what makes the flag honest.
//
// Same shape as packages/themes/neutral/scripts/build-theme.mjs, and the same
// two requirements: @astryx-svelte/core must be built first (this imports the
// compiled theme compiler out of its dist/), and Node's type stripping has to be
// on so the theme definition can stay TypeScript. `pnpm -r build` orders the
// first; the `--experimental-strip-types` flag in package.json handles the
// second. That flag is a no-op from Node 22.18, where stripping is on by
// default, but the floor here is 22.17 (port/todo.md → Phase 0).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DOCS_ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT_DIR = path.join(DOCS_ROOT, 'src', 'lib', 'generated');
const OUT_FILE = path.join(OUT_DIR, 'astryx-theme.css');

const HEADER = `/* @generated by scripts/build-astryx-theme.mjs — do not edit.
 *
 * The docsite's Astryx brand theme, compiled from src/lib/themes/astryx-theme.ts.
 * Imported by routes/+layout.svelte; the theme object it pairs with carries
 * \`__built\`, so <Theme> injects nothing at runtime.
 */
`;

/**
 * Emit the theme stylesheet.
 *
 * The two imports are dynamic so a caller that only wants the module (the Vite
 * plugin, at config time) doesn't pay for resolving core's dist before it has
 * been built.
 *
 * @param {{quiet?: boolean}} [options]
 */
export async function buildAstryxTheme({ quiet = false } = {}) {
	// Deep dist paths, not the `@astryx-svelte/core/theme` subpath: that barrel
	// re-exports `theme.svelte`, and Node cannot load a `.svelte` file. Same
	// reason packages/themes/neutral/src/neutral-theme.ts reaches in this way.
	const CORE_THEME = path.join(DOCS_ROOT, '..', 'packages', 'core', 'dist', 'theme');
	const { generateThemeCss } = await import(
		pathToFileURL(path.join(CORE_THEME, 'generate-theme-rules.js')).href
	);
	const { defineTheme } = await import(
		pathToFileURL(path.join(CORE_THEME, 'define-theme.js')).href
	);
	// Both of these are `.ts` with type-only imports, so Node's stripping erases
	// everything and neither has to resolve the barrel.
	const { createAstryxThemeConfig } = await import(
		pathToFileURL(path.join(DOCS_ROOT, 'src', 'lib', 'themes', 'astryx-theme-config.ts')).href
	);
	const { BRAND } = await import(
		pathToFileURL(path.join(DOCS_ROOT, 'src', 'lib', 'landing', 'constants.ts')).href
	);

	const css = HEADER + generateThemeCss(defineTheme(createAstryxThemeConfig(BRAND)));

	fs.mkdirSync(OUT_DIR, { recursive: true });

	// Don't touch the file when nothing changed — the Vite content plugin watches
	// src/lib/generated/, and an unconditional write would loop the dev server.
	// Same contract as generate-content.mjs's `writeIfChanged`.
	const existing = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null;
	const changed = existing !== css;
	if (changed) fs.writeFileSync(OUT_FILE, css, 'utf8');

	if (!quiet) {
		console.log(
			`  astryx-theme.css — ${(Buffer.byteLength(css) / 1024).toFixed(1)} KB${changed ? '' : ' (unchanged)'}`
		);
	}

	return { changed, css };
}

// Run directly (`node scripts/build-astryx-theme.mjs`) as well as via the plugin.
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	console.log('building the astryx theme…');
	buildAstryxTheme().catch((error) => {
		console.error(`\nbuild-astryx-theme failed: ${error.message}\n`);
		process.exit(1);
	});
}
